create table if not exists payment_transactions (
    currency varchar(3) not null,
    excess boolean default false not null,
    amount_minor bigint not null,
    booking_id bigint not null,
    checkout_expires_at timestamp(6),
    completed_at timestamp(6),
    created_at timestamp(6) not null,
    customer_id bigint,
    id bigint generated by default as identity,
    reversal_attempted_at timestamp(6),
    updated_at timestamp(6) not null,
    payment_type varchar(20) not null check (payment_type in ('FULL','ADVANCE','REMAINING')),
    provider varchar(20) not null check (provider in ('STRIPE')),
    reversal_status varchar(20) check (reversal_status in ('NOT_REQUIRED','PENDING','SUCCEEDED','FAILED')),
    status varchar(20) not null check (status in ('INITIATED','CHECKOUT_CREATED','SUCCEEDED','FAILED','CANCELLED','EXPIRED')),
    reversal_error varchar(500),
    checkout_url varchar(1024),
    checkout_session_id varchar(255) unique,
    payment_intent_id varchar(255),
    reversal_refund_id varchar(255),
    primary key (id)
);

