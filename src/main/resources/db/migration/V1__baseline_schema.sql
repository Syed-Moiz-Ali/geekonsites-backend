-- =============================================================================
-- PHASE 8 — V1 baseline schema
-- =============================================================================
-- This is the canonical, PostgreSQL-only baseline of the GeekOnSites schema as it
-- exists after Phases 0-7. It was generated from the JPA entity model with
-- Hibernate's PostgreSQLDialect (CamelCaseToUnderscores physical naming) and then
-- made idempotent, so it is safe on BOTH:
--   * a fresh, empty database  -> creates the whole schema; and
--   * a pre-Flyway existing DB -> every statement is a no-op (the objects already
--                                 exist), and Flyway records the version.
--
-- Do NOT edit the meaning of this file after it has been applied anywhere: add a
-- new V<n> migration instead.
--
-- Every table uses `CREATE TABLE IF NOT EXISTS`; every index uses
-- `CREATE INDEX IF NOT EXISTS`; the two FK constraints that Hibernate itself
-- declares (token -> users) are guarded by a catalog check.
-- =============================================================================

create table if not exists agents (
    id bigint generated by default as identity,
    city varchar(255),
    country varchar(255),
    email varchar(255) unique,
    name varchar(255),
    phone varchar(255),
    status varchar(255),
    primary key (id)
);

create table if not exists users (
